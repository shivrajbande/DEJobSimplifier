products_table_text = '''
Table Name: products

Purpose:
Stores catalog information about items available for sale, including pricing, category, brand, and inventory.

Columns:
- product_id: Unique identifier for each product
- name: Name of the product
- category: Category classification (e.g., Electronics, Clothing)
- price: Selling price of the product
- stock: Available inventory quantity
- brand: Brand or manufacturer name
- rating: Average customer rating (1 to 5)
- supplier: Vendor or supplier providing the product

Relationships:
- A product can appear in multiple order items
- products.product_id connects to order_items.product_id

Analytical Usage:
- Used to identify top selling products based on quantity or revenue
- Used in revenue calculations when joined with order_items
- Helps filter products by category, brand, or price range

Query Patterns:
- Top selling products by quantity
- Revenue generated by each product
- Products with low stock
'''

customer_table_text = '''
Table Name: customers

Purpose:
Stores customer identity, contact, and location information.

Columns:
- customer_id: Unique identifier for each customer
- first_name: First name of the customer
- last_name: Last name of the customer
- email: Email address used for communication
- phone: Contact phone number
- address: Physical address of the customer
- city: City of residence
- state: State of residence
- zip_code: Postal code

Relationships:
- One customer can place multiple orders
- customers.customer_id connects to orders.customer_id

Analytical Usage:
- Used to analyze customer behavior and purchase patterns
- Used in aggregation queries with orders
- Helps group data by location (city/state)

Query Patterns:
- Customers with highest number of orders
- Customers with highest total spend
- Customers from a specific city
'''

orders_table_text = '''
Table Name: orders

Purpose:
Stores high-level transaction data for each customer order including date, status, and total value.

Columns:
- order_id: Unique identifier for each order
- customer_id: Reference to customer placing the order
- order_date: Date of order placement
- status: Order status (PLACED, SHIPPED, DELIVERED)
- total_amount: Total value of the order
- shipping_address: Delivery address
- shipping_city: Delivery city
- shipping_state: Delivery state
- shipping_zip: Delivery postal code

Relationships:
- Each order belongs to one customer
- orders.customer_id connects to customers.customer_id
- One order can contain multiple order items
- orders.order_id connects to order_items.order_id
- Each order has a payment record
- orders.order_id connects to payments.order_id

Analytical Usage:
- Used to calculate total revenue
- Used to count number of orders per customer
- Used in time-based analysis (daily, monthly trends)
- Central table for joins between customers, products, and payments

Query Patterns:
- Customers with highest number of orders
- Total orders per customer
- Revenue over time
- Orders by status (delivered, pending)
'''

order_items_table_text = '''
Table Name: order_items

Purpose:
Stores detailed line-item data for each product included in an order.

Columns:
- order_item_id: Unique identifier for each order item
- order_id: Reference to the order
- product_id: Reference to the product
- quantity: Number of units purchased
- price: Price per unit at time of purchase
- discount: Discount applied to the item
- tax: Tax applied to the item
- total: Final amount for this item (price * quantity - discount + tax)

Relationships:
- Each order item belongs to one order
- order_items.order_id connects to orders.order_id
- Each order item refers to one product
- order_items.product_id connects to products.product_id

Analytical Usage:
- Used to calculate product-level revenue
- Used to identify most sold products by quantity
- Enables joins between orders and products
- Used in aggregation queries (SUM, COUNT)

Query Patterns:
- Most sold products
- Revenue per product
- Average order value
- Total quantity sold per product
'''

payments_table_text = '''
Table Name: payments

Purpose:
Stores financial transaction details associated with orders.

Columns:
- payment_id: Unique identifier for each payment
- order_id: Reference to the associated order
- payment_method: Payment method (UPI, CARD, NETBANKING)
- payment_status: Status (SUCCESS, FAILED, PENDING)
- amount: Amount paid
- transaction_id: External payment transaction ID
- payment_date: Date of transaction
- currency: Currency used (e.g., INR)
- gateway: Payment gateway (Razorpay, Stripe)

Relationships:
- Each payment is linked to one order
- payments.order_id connects to orders.order_id

Analytical Usage:
- Used to analyze payment success/failure rates
- Used to filter revenue based on successful payments
- Helps detect failed or pending transactions

Query Patterns:
- Failed payments
- Payment method distribution
- Successful payments revenue
'''

